# Match your internal codec by name; adjust if needed (e.g., "ALC298", "Realtek", "Cirrus", etc.)
CODEC_MATCH_REGEX="${CODEC_MATCH_REGEX:-Realtek|ALC}"

require() { command -v "$1" >/dev/null 2>&1 || { echo "Missing: $1" >&2; exit 2; }; }
require hda-verb

pick_hwdep() {
  local f card codec cardnum codecid dev
  for f in /proc/asound/card*/codec#*; do
    [[ -r "$f" ]] || continue
    if grep -Eq "^[[:space:]]*Codec:[[:space:]].*(${CODEC_MATCH_REGEX})" "$f"; then
      card="$(basename "$(dirname "$f")")"   # e.g., card1
      codec="$(basename "$f")"               # e.g., codec#0
      cardnum="${card#card}"                 # -> 1
      codecid="${codec#codec#}"              # -> 0
      dev="/dev/snd/hwC${cardnum}D${codecid}"
      [[ -e "$dev" ]] && { echo "$dev"; return 0; }
    fi
  done
  return 1
}

